"""Package a generated BPMN2 iFlow into a Cloud Integration design-time bundle.

The Integration Suite design-time OData API (`IntegrationDesigntimeArtifacts`)
expects `ArtifactContent` to be the base64 of a ZIP with the iFlow project
layout that CPI exports:

  META-INF/MANIFEST.MF
  src/main/resources/scenarioflows/integrationflow/<Id>.iflw
  src/main/resources/parameters.prop
  src/main/resources/parameters.propdef
  metainfo.prop

This builder produces that structure with an OSGi/SAP bundle manifest so the
artifact is accepted into the package. The generated .iflw is a skeleton — the
sender/receiver channels still need adapter configuration in the Web IDE before
the flow is fully runnable.
"""
from __future__ import annotations

import io
import zipfile

# Ordered manifest headers. Manifest-Version MUST come first. The long
# Import-Package value is wrapped to the OSGi 72-byte line limit by _manifest().
_IMPORT_PACKAGE = (
    'com.sap.esb.application.services.cxf.interceptor,com.sap.esb.webservice.'
    'audit.log,com.sap.security.api.ssf,javax.jws,javax.wsdl,javax.xml.bind,'
    'javax.xml.bind.annotation,javax.xml.namespace,javax.xml.ws,'
    'org.apache.camel;version="2.8",org.apache.camel.builder;version="2.8",'
    'org.apache.camel.builder.xml;version="2.8",org.apache.camel.component.cxf,'
    'org.apache.camel.model;version="2.8",org.apache.camel.processor;version="2.8",'
    'org.apache.camel.spi;version="2.8",org.apache.commons.logging,'
    'org.osgi.framework;version="1.6.0",org.slf4j;version="1.6"'
)


def _manifest(iflow_id: str, iflow_name: str) -> str:
    """Build a MANIFEST.MF, wrapping every header to the OSGi/JAR 72-byte line
    limit (continuation lines start with a single space), CRLF-terminated."""
    headers = [
        ("Manifest-Version", "1.0"),
        ("Bundle-ManifestVersion", "2"),
        ("Bundle-SymbolicName", f"{iflow_id}; singleton:=true"),
        ("Bundle-Name", iflow_name),
        ("Bundle-Version", "1.0.0"),
        ("SAP-BundleType", "IntegrationFlow"),
        ("SAP-NodeType", "IFLMAP"),
        ("SAP-RuntimeProfile", "iflmap"),
        ("Origin-Bundle-Name", iflow_name),
        ("Origin-Bundle-SymbolicName", iflow_id),
        ("Origin-Bundle-Version", "1.0.0"),
        ("Import-Package", _IMPORT_PACKAGE),
    ]
    lines: list[str] = []
    for key, value in headers:
        logical = f"{key}: {value}".encode("utf-8")
        # first physical line ≤ 72 bytes; continuations ≤ 71 bytes + leading space
        lines.append(logical[:72].decode("utf-8"))
        rest = logical[72:]
        while rest:
            lines.append(" " + rest[:71].decode("utf-8"))
            rest = rest[71:]
    return "\r\n".join(lines) + "\r\n"


_PARAMETERS_PROP = "#Integration flow generated by RCA Smart Copilot\n"
_PARAMETERS_PROPDEF = ('<?xml version="1.0" encoding="UTF-8" standalone="no"?>'
                       '<parameters><param_references/></parameters>')
_METAINFO = "#Store metainfo properties\ndescription=\n"
_PROJECT = ('<?xml version="1.0" encoding="UTF-8"?><projectDescription>'
            '<name>{id}</name><comment/><projects/>'
            '<buildSpec><buildCommand><name>org.eclipse.jdt.core.javabuilder</name>'
            '<arguments/></buildCommand></buildSpec>'
            '<natures><nature>org.eclipse.jdt.core.javanature</nature>'
            '<nature>com.sap.ide.ifl.project.support.project.nature</nature>'
            '<nature>com.sap.ide.ifl.bsn</nature></natures></projectDescription>')


# uploaded-file kind → project resource folder (unreferenced; the user wires
# them to steps in the Web IDE). Binary/empty attachments are skipped.
_RES_FOLDER = {
    "groovy": "src/main/resources/script/",
    "js": "src/main/resources/script/",
    "xsd": "src/main/resources/xsd/",
    "wsdl": "src/main/resources/wsdl/",
    "xslt": "src/main/resources/mapping/",
    "xml": "src/main/resources/",
    "json": "src/main/resources/",
    "text": "src/main/resources/",
}


def build_iflow_zip(iflow_id: str, iflow_name: str, bpmn_xml: str,
                    resources: list[dict] | None = None) -> bytes:
    """Return the bytes of a CPI-importable iFlow project ZIP.

    `resources` are uploaded attachments ({name, kind, content}); those with
    text content are bundled into the project so they exist in the tenant for
    the user to attach to Script/Mapping steps."""
    safe_id = (iflow_id or "iFlow").strip()
    safe_name = (iflow_name or safe_id).strip()
    buf = io.BytesIO()
    seen: set[str] = set()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("META-INF/MANIFEST.MF", _manifest(safe_id, safe_name))
        z.writestr(".project", _PROJECT.format(id=safe_id))
        z.writestr(f"src/main/resources/scenarioflows/integrationflow/{safe_name}.iflw", bpmn_xml or "")
        z.writestr("src/main/resources/parameters.prop", _PARAMETERS_PROP)
        z.writestr("src/main/resources/parameters.propdef", _PARAMETERS_PROPDEF)
        z.writestr("metainfo.prop", _METAINFO)
        for r in (resources or []):
            name = (r.get("name") or "").strip()
            content = r.get("content") or ""
            if not name or not content:
                continue  # skip binary/empty (e.g. zip, iflw, image)
            folder = _RES_FOLDER.get(r.get("kind", "text"), "src/main/resources/")
            path = folder + name
            if path in seen:
                continue
            seen.add(path)
            z.writestr(path, content)
    return buf.getvalue()
